#!/bin/bash
set -e

echo "=========================================="
echo "?? ?????? ??????????????? ?????????????..."
echo "=========================================="

if [ "$EUID" -ne 0 ]; then
    echo "? ??????: ????????? ?????? ? ??????? root (sudo bash deploy.sh)"
    exit 1
fi

APP_DIR="/opt/not_a_music"
CURRENT_DIR=$(pwd)

echo "?? ?????????? ??????? ? ????????? ????????????..."
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y --no-install-recommends     python3     python3-pip     python3-venv     ffmpeg     curl     git

if ! command -v mongod &> /dev/null && ! command -v mongodb &> /dev/null; then
    echo "?? ????????? MongoDB..."
    apt-get install -y --no-install-recommends mongodb || true
fi

systemctl daemon-reload || true
systemctl enable mongod 2>/dev/null || systemctl enable mongodb 2>/dev/null || true
systemctl restart mongod 2>/dev/null || systemctl restart mongodb 2>/dev/null || true

echo "?? ?????????? ????? ??????????: $APP_DIR"
mkdir -p "$APP_DIR"

if [ "$CURRENT_DIR" != "$APP_DIR" ]; then
    echo "?? ??????????? ?????? ???????..."
    cp -r "$CURRENT_DIR"/* "$APP_DIR"/ 2>/dev/null || true
fi

cd "$APP_DIR"

echo "?? ???????? ???????????? ????????? Python 3..."
python3 -m venv venv
./venv/bin/pip install --upgrade pip setuptools wheel
./venv/bin/pip install -r requirements.txt

if [ ! -f .env ]; then
    echo "?? ???????? ???????????? ????? .env..."
    cat << 'ENVEOF' > .env
MONGO_URI='mongodb://127.0.0.1:27017'
MONGO_DB_NAME='nt_music'
BOT_TOKEN='YOUR_BOT_TOKEN_HERE'

USER_SAVED_LIMIT=50
FAV_PAGE_SIZE=10
TRACKS_MAX=50
PLAYLISTS_MAX=25
SEARCH_LIMIT=7
AD_EVERY_N=5
DEFAULT_LANG=ru
IS_DW_ALL=False
SUDO_ADMIN=7194401988
ENVEOF
    echo "? ?? ???????? ??????? ????? ? /opt/not_a_music/.env"
fi

SERVICE_FILE="/etc/systemd/system/not_a_music.service"
echo "?? ????????? ?????? systemd ($SERVICE_FILE)..."

cat << 'SVCEOF' > "$SERVICE_FILE"
[Unit]
Description=Not A Music Telegram Bot
After=network.target mongod.service mongodb.service

[Service]
Type=simple
User=root
WorkingDirectory=/opt/not_a_music
ExecStart=/opt/not_a_music/venv/bin/python main.py
Restart=always
RestartSec=5
StandardOutput=journal
StandardError=journal
SyslogIdentifier=not_a_music

[Install]
WantedBy=multi-user.target
SVCEOF

systemctl daemon-reload
systemctl enable not_a_music
systemctl restart not_a_music || true

echo "=========================================="
echo "? ????????????? ??????? ?????????!"
echo "???????? ???????: systemctl status not_a_music"
echo "???????? ?????:   journalctl -u not_a_music -f"
echo "=========================================="
